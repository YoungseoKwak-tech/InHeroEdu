import Anthropic from "@anthropic-ai/sdk";
import { NextRequest } from "next/server";
import { getAiFallback, getAiRouteGuard } from "@/lib/ai-access";
import { AI_MODELS } from "@/lib/ai-models";
import { getAnthropicApiKey } from "@/lib/env";
import type {
  TrajectoryAnalyzeResponse,
  TrajectoryBuildResponse,
  TrajectoryScaffoldResponse,
  TrajectoryDeployResponse,
} from "@/lib/trajectory-lab";

const client = new Anthropic({
  apiKey: getAnthropicApiKey(),
});

type ChatMessage = {
  role: "user" | "assistant";
  content: string;
};

type TrajectoryChatRequest = {
  message: string;
  history?: ChatMessage[];
  analyze?: TrajectoryAnalyzeResponse | null;
  build?: TrajectoryBuildResponse | null;
  scaffold?: TrajectoryScaffoldResponse | null;
  deploy?: TrajectoryDeployResponse | null;
  portraitSummary?: string | null;
  intakeContext?: {
    keywords?: string[];
    activities?: string[];
    interests?: string[];
    strengths?: string[];
    frictions?: string[];
    heroCode?: string;
  } | null;
  lang?: "ko" | "en";
};

function buildSystemPrompt(lang: "ko" | "en", hasTrajectory: boolean) {
  const languageRule =
    lang === "ko"
      ? "Respond in Korean. Keep English names for product names or technical terms only when useful."
      : "Respond in English.";

  if (!hasTrajectory) {
    return `You are InHero's Trajectory Intake Coach.
${languageRule}

Your role:
- help a student uncover interests, repeated patterns, meaningful activities, frustrations, and what they want to build
- start with curiosity-first intake questions when the student is new
- ask one focused question at a time when possible
- help the student turn vague interests into clearer signal
- sound like a thoughtful strategist, not a generic chatbot
- remember that InHero is a student-specific engine, so the best ideas often come from the student's actual study friction, identity struggle, or learning pattern
- if useful, gently ask about subjects they return to, activities so far, people they want to help, and what kind of problem they would love to solve
- do not jump into a final build recommendation too early
- do not drift into generic college advice
- if the student explicitly says things like "build now", "host now", "just build it", or asks for the first version immediately, and the intake context already contains clear signal, stop asking broad intake questions and give a provisional first build direction right away
- in that fast-path case, provide:
  - a likely product direction
  - the first feature to build
  - a realistic student-friendly stack and hosting path
  - 2-4 next moves
- label it as a first best-fit direction based on current signal, not as a final identity verdict

Style rules:
- be smart, specific, and momentum-creating
- treat the student like a real founder-builder in formation
- keep answers concise but warm
- if you suggest a web MVP, prefer a credible student-friendly default like Next.js + Tailwind + Vercel, and only go simpler if the student is clearly brand new
- use direct questions like:
  - What subjects keep pulling you back?
  - What have you already done or tried?
  - Who do you want to help?
  - What kind of thing do you wish existed?
- when the student shares enough signal, summarize what you are hearing in 3-5 bullets and suggest running Trajectory Lab next
`;
  }

  return `You are InHero's Trajectory Build Coach.
${languageRule}

Your role:
- help a student refine a product/app/web/initiative idea generated by Trajectory Lab
- answer concrete questions about MVP scope, features, positioning, landing page framing, audience, hosting, and launch order
- stay practical and builder-oriented
- do not drift into generic college advice unless it directly helps the build
- prioritize first shippable steps over abstract brainstorming

Style rules:
- be smart, specific, and momentum-creating
- treat the student like a real founder-builder, not like a passive user
- keep answers concise but actionable
- whenever helpful, suggest the next 2-4 concrete moves
- if asked about hosting, suggest a realistic student-friendly path such as Next.js + Tailwind + Vercel, with Supabase only when the MVP actually needs data or auth
`;
}

function buildContextBlock(payload: TrajectoryChatRequest) {
  const analyze = payload.analyze;
  const build = payload.build;
  const scaffold = payload.scaffold;
  const deploy = payload.deploy;
  const intake = payload.intakeContext;
  const portraitSummary = payload.portraitSummary;

  return `Trajectory context:
${analyze ? `- trajectory: ${analyze.trajectory}
- buildDirection: ${analyze.buildDirection}
- signalSummary: ${analyze.signalSummary.join(" | ")}
- recommendedFormat: ${analyze.recommendedFormat}
- suggestedProjectTypes: ${analyze.suggestedProjectTypes.join(" | ")}
- mvpConcept: ${analyze.mvpConcept.name} — ${analyze.mvpConcept.oneLiner}
` : "- trajectory: not available"}
${build ? `- productName: ${build.productName}
- tagline: ${build.tagline}
- audience: ${build.audience}
- problemStatement: ${build.problemStatement}
- coreFeatures: ${build.coreFeatures.join(" | ")}
- userFlow: ${build.userFlow.join(" | ")}
- mvpScope: ${build.mvpScope.join(" | ")}
` : ""}
${scaffold ? `- template: ${scaffold.template}
- pages: ${scaffold.pages.join(" | ")}
- components: ${scaffold.components.join(" | ")}
` : ""}
${deploy ? `- deployHost: ${deploy.host}
- preview: ${deploy.previewUrl ?? deploy.previewSlug}
- recommendedCommand: ${deploy.recommendedCommand}
` : ""}
${intake ? `- intake keywords: ${intake.keywords?.join(" | ") || "(none yet)"}
- intake activities: ${intake.activities?.join(" | ") || "(none yet)"}
- intake interests: ${intake.interests?.join(" | ") || "(none yet)"}
- intake strengths: ${intake.strengths?.join(" | ") || "(none yet)"}
- intake frictions: ${intake.frictions?.join(" | ") || "(none yet)"}
- intake heroCode: ${intake.heroCode || "(unknown)"}
` : ""}
${portraitSummary ? `- InHero memory summary: ${portraitSummary}` : ""}`;
}

export async function POST(req: NextRequest) {
  const guard = getAiRouteGuard("trajectory-lab-chat");
  if (guard) return Response.json(guard);

  const payload = (await req.json()) as TrajectoryChatRequest;
  const { message, history = [], lang = "en" } = payload;

  if (!message?.trim()) {
    return Response.json({ error: "message is required" }, { status: 400 });
  }

  try {
    const hasTrajectory = Boolean(payload.analyze && payload.build);
    const response = await client.messages.create({
      model: AI_MODELS.trajectoryChat,
      max_tokens: 500,
      system: `${buildSystemPrompt(lang, hasTrajectory)}\n\n${buildContextBlock(payload)}`,
      messages: [...history, { role: "user", content: message.trim() }],
    });

    const reply = response.content[0]?.type === "text" ? response.content[0].text.trim() : "";
    return Response.json({ reply });
  } catch (error) {
    return Response.json(getAiFallback("trajectory-lab-chat", error));
  }
}
